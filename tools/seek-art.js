#!/usr/bin/env node
// 🔍 Builds scripts/seek-art.js — the pictures Seek & Find draws — from Google's
// Noto emoji art (Apache License 2.0; NOTO-LICENSE.txt), taking ONLY the
// pictures SeekLogic.artNames() says a place can draw.
//
//   node tools/seek-art.js <dir holding icons.json>   (rebuild)
//   node tools/seek-art.js                            (check the shipped one)
//
// The source is the @iconify-json/noto npm package (its icons.json is every
// Noto picture as an SVG body). The pictures are copied EXACTLY: rounding
// their numbers looked like a free third off the file and broke 167 of 175 of
// them (a gradient's matrix carries tiny coefficients, and a path runs numbers
// together, "9.71.99"), measured by drawing every one both ways. Never
// hand-edit the output; re-run this.
"use strict";
const fs = require("fs");
const path = require("path");
const L = require("../scripts/seek-logic.js");

const dir = process.argv[2];
// With no source folder it CHECKS the shipped bundle (the map-gen.js
// precedent): every picture a place can draw is there and is a whole svg.
if (!dir) {
  const ART = require("../scripts/seek-art.js");
  const want = L.artNames();
  const gone = want.filter((n) => !/^<svg[\s\S]+<\/svg>$/.test(ART[n] || ""));
  const extra = Object.keys(ART).filter((n) => want.indexOf(n) < 0);
  if (gone.length || extra.length) { console.error("missing: " + gone.join(", ") + " | not drawn: " + extra.join(", ")); process.exit(1); }
  console.log(want.length + " pictures, all present");
  process.exit(0);
}
const src = JSON.parse(fs.readFileSync(path.join(dir, "icons.json"), "utf8"));
const icons = src.icons, aliases = src.aliases || {};
const W = src.width || 128, H = src.height || 128;

function resolve(name) {
  if (icons[name]) return icons[name];
  const a = aliases[name];
  if (a && icons[a.parent] && !a.hFlip && !a.vFlip && !a.rotate) return icons[a.parent];
  return null;
}
const out = {};
const missing = [];
let raw = 0;
for (const name of L.artNames()) {
  const ic = resolve(name);
  if (!ic) { missing.push(name); continue; }
  const w = ic.width || W, h = ic.height || H;
  const body = ic.body;
  raw += body.length;
  out[name] = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + w + " " + h + '">' + body + "</svg>";
}
if (missing.length) { console.error("missing pictures: " + missing.join(", ")); process.exit(1); }

const head =
  "// 🔍 GENERATED by tools/seek-art.js — never hand-edit; re-run the tool.\n" +
  "// The pictures Seek & Find draws: Noto Emoji art, Copyright Google Inc.,\n" +
  "// licensed under the Apache License, Version 2.0 (see NOTO-LICENSE.txt);\n" +
  "// from https://github.com/googlefonts/noto-emoji via the @iconify-json/noto\n" +
  "// package, unchanged.\n";
const body = "(function (global) {\n  \"use strict\";\n  const SeekArt = " + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ";\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = SeekArt;\n  global.SeekArt = SeekArt;\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
fs.writeFileSync(path.join(__dirname, "..", "scripts", "seek-art.js"), head + body);
console.log("pictures " + Object.keys(out).length + ", bytes " + raw);
